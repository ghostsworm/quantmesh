def convert_content(text: str) -> str:
    for s, t in S2T:
        text = text.replace(s, t)
    return text


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    exts = (".go", ".ts", ".tsx", ".js", ".css")
    skip_dirs = {"node_modules", ".git", "dist", "vendor", "__pycache__"}
    count = 0
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in skip_dirs]
        for name in filenames:
            if not name.endswith(exts):
                continue
            path = os.path.join(dirpath, name)
            if "scripts/s2t" in path or "s2t_comments" in path:
                continue
            try:
                with open(path, "r", encoding="utf-8") as f:
                    raw = f.read()
            except Exception:
                continue
            if not re.search(r"[\u4e00-\u9fff]", raw):
                continue
            out = convert_content(raw)
            if out != raw:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(out)
                count += 1
                print(path)
    print(f"Converted {count} files.")


if __name__ == "__main__":
    main()
